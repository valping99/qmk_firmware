static void print_status_narrow(void) {
    // Print current mode
    uint8_t highest_layer = get_highest_layer(layer_state);
    bool is_base_default = get_highest_layer(default_layer_state) == _QWERTY;
    bool is_gaming_default = get_highest_layer(default_layer_state) == _GAMING;
    bool is_disable_default = get_highest_layer(default_layer_state) == _DISABLE;

    render_master_logo();
    oled_set_cursor(0, 4);
    oled_write_ln_P(PSTR("LAYER"), false);
  	switch (highest_layer)
	{
        case _QWERTY:
        case _GAMING:
		case _DISABLE:
		if(is_base_default){
            oled_write_P(PSTR("Base\n"), false);
		}
		else if(is_gaming_default){
            oled_write_P(PSTR("Game\n"), false);
		}
		else if(is_disable_default){
            oled_write_P(PSTR("Sleep\n"), false);
		}
            break;
        case _RAISE:
            oled_write_P(PSTR("Raise"), false);
            break;
        case _LOWER:
            oled_write_P(PSTR("Lower"), false);
            break;
        case _ADJUST:
            oled_write_P(PSTR("Adju\n"), false);
            break;
        default:
            oled_write_ln_P(PSTR("Unkn\n"), false);
            break;

    }

    oled_write_P(PSTR("\n"), false);
}

void render_wpm_status(void) {
    oled_write_P(PSTR(" WPM\n "), false);
    if (timer_elapsed32(last_typing_time) < 1000) {
        last_wpm = get_current_wpm();
    } else {
        last_wpm = 0;
    }

    char wpm_str[4];
    snprintf(wpm_str, sizeof(wpm_str), "%03d", last_wpm);
    oled_write(wpm_str, false);
}

void render_user_status(void) {
    led_t led_usb_state = host_keyboard_led_state();

    if (led_usb_state.caps_lock) {
        oled_write_ln_P(PSTR("Caps\n"), led_usb_state.caps_lock);
    } else if (led_usb_state.num_lock) {
        oled_write_ln_P(PSTR("Num \n"), led_usb_state.num_lock);
    } else if (led_usb_state.scroll_lock) {
        oled_write_ln_P(PSTR("Scrol\n"), led_usb_state.scroll_lock);
    } else {
        oled_write_ln_P(PSTR("_____"), false);
    }
}

oled_rotation_t oled_init_user(oled_rotation_t rotation) {
    if (is_keyboard_master())
    {
        return OLED_ROTATION_270;
    }
else{
        return OLED_ROTATION_180;
    }
    return rotation;
}

bool oled_task_user(void) {
    if (is_keyboard_master()) {
        print_status_narrow();
        render_user_status();
        render_wpm_status();
    }

    return false;
}
